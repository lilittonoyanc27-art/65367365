const LOCAL_STORAGE_KEY = 'espanol_interactivo_rio_plata_lyrics_v1';

export function loadSavedLyrics(): LyricLine[] {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.warn('Failed to load lyrics from localStorage:', e);
  }
  return INITIAL_RAW_LYRICS;
}

export function saveLyricsToStorage(lines: LyricLine[]): void {
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(lines));
  } catch (e) {
    console.warn('Failed to save lyrics to localStorage:', e);
  }
}

export function resetLyricsToDefault(): LyricLine[] {
  try {
    localStorage.removeItem(LOCAL_STORAGE_KEY);
  } catch (e) {
    console.warn(e);
  }
  return INITIAL_RAW_LYRICS;
}
